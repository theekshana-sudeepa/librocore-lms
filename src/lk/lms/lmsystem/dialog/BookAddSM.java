    private boolean bNameValidation(String value) {
        if (value.isEmpty()) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Book Name Is Required");
            return true;
        } else if (!value.matches("^[a-zA-Z\\s]+$")) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Only Letters Allowed In Book Name.");
            return true;
        } else {
            return false;
        }
    }

    private boolean bAuthorValidation(String value) {
        if (value.isEmpty()) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Book Author Name Is Required");
            return true;
        } else if (!value.matches("^[a-zA-Z\\s]+$")) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Only Letters Allowed In Book Author Name.");
            return true;
        } else {
            return false;
        }
    }

