    private void bookAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bookAddActionPerformed

        SimpleDateFormat dformat = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");

        long bookId = System.currentTimeMillis();
        String bookstr = String.valueOf(bookId);

        String bname = bookName.getText();
        String bauthor = bookAuthor.getText();
        String bprice = bookPrice.getText();

        int catComboBox = this.catComboBox.getSelectedIndex();
        int subCatComboBox = this.subCatComboBox.getSelectedIndex();

        if (catComboBox < 1) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT, "Select Main category");
            return;
        }
        if (subCatComboBox < 1) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT, "Select Main category");
            return;
        }

        if (bNameValidation(bname)) {
            return;
        }
        if (bAuthorValidation(bauthor)) {
            return;
        }

        if (jDateChooser2 != null) {
            Date pubdate = jDateChooser2.getDate();
            if (pubdate != null) {
                SimpleDateFormat format = new SimpleDateFormat("yyyy-MM-dd");
                String pubdatestr = format.format(pubdate);

                // rest of your code
            } else {
                Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT, "Select Published Date");
                jDateChooser2.grabFocus();
                return;
            }

            if (bPriceValidation(bprice)) {
                return;
            }

            SimpleDateFormat format = new SimpleDateFormat("yyyy-MM-dd");
            String pubdatestr = format.format(pubdate);

            HashMap<String, Object> parameters = new HashMap<>();
            parameters.put("BookID", bookstr);
            parameters.put("BookName", bname);
            parameters.put("BookAuthor", bauthor);

            try {
                String path = "/reports/LMSBookBCode.jasper";
                InputStream reportStream = getClass().getResourceAsStream(path);
                if (reportStream == null) {
                    throw new FileNotFoundException("Report file not found: " + path);
                }

                // Data source (if any, here using a bean collection data source)
                JREmptyDataSource dataSource = new JREmptyDataSource();

                //fill report with data
                JasperPrint jasperPrint = JasperFillManager.fillReport(reportStream, parameters, dataSource);

                //Export report to pdf
                String outputFolder = "src/bookqrcodes/";
                String outputFile = "book" + bookstr + ".pdf";
                File outputfile = new File(outputFolder, outputFile);
                JasperExportManager.exportReportToPdfFile(jasperPrint, outputfile.getAbsolutePath());

                Notifications
                        .getInstance()
                        .show(Notifications.Type.SUCCESS,
                                Notifications.Location.TOP_RIGHT, "PDF saved Successfully.");

                //view report
                JFrame frame = new JFrame("Report");
                frame.getContentPane().add(new JRViewer(jasperPrint));
                frame.pack();
                frame.setVisible(true);

                try {
                    synchronized (this) {
                        ResultSet result = MySQL.search("SELECT `id` FROM `book` WHERE `book`.`id`='" + bookstr + "'");
                        if (result.next()) {
                            Notifications
                                    .getInstance()
                                    .show(Notifications.Type.WARNING,
                                            Notifications.Location.TOP_RIGHT, "This Book Already Exists!");
                        } else {

                            try {
                                String joinedDate = dformat.format(new Date());
                                MySQL.iud("INSERT INTO `book`(`id`,`main_category_id`,`sub_category_id`,`name`,`book_author`,`published_date`,`added_date`,`price`,`book_qr`) "
                                        + "VALUES ('" + bookstr + "','" + catComboBox + "','" + subCatComboBox + "','" + bname + "','" + bauthor + "','" + pubdatestr + "','" + joinedDate + "','" + bprice + "','" + outputFile + "')"
                                );
                            } catch (Exception e) {
                                e.printStackTrace();
                            }

                            Notifications
                                    .getInstance()
                                    .show(Notifications.Type.SUCCESS,
                                            Notifications.Location.TOP_RIGHT, "Book Details Added Successfully.");

                        }
                    }
                } catch (SQLException se) {
                    throw new RuntimeException(se);
                }

            } catch (Exception e) {
                e.printStackTrace();
            }

        } else {
            // handle the null case
        }


    }//GEN-LAST:event_bookAddActionPerformed

