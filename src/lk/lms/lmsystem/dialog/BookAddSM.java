    private boolean bPriceValidation(String value) {
        if (value.isEmpty()) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Book Price Is Required");
            return true;
        }
        try {
            double price = Double.parseDouble(value);
            if (price <= 0) {
                Notifications
                        .getInstance()
                        .show(Notifications.Type.WARNING,
                                Notifications.Location.TOP_RIGHT, "Book Price Must Be Greater Than Zero");
                return true;
            }
        } catch (NumberFormatException e) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Invalid Book Price. Please Enter A Valid Number");
            return true;
        }

        return false;
    }

