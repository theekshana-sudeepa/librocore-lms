    private void roundButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_roundButton1ActionPerformed
        // TODO add your handling code here:

        String fname = fnameField.getText();
        String lname = lnameField.getText();
        String nicNo = nicField.getText();
        String message = feedbackField.getText();

        if (fnameValidation(fname)) {
            return;
        }
        if (lnameValidation(lname)) {
            return;
        }

        if (nicValidate(nicNo)) {
            return;
        }

        if (feedbackValidate(message)) {
            return;
        }
        
         try {

            MySQL.iud("INSERT INTO `feedback`(`fname`,`lname`,`nic_no`,`message`) "
                    + "VALUES ('" + fname+ "','" + lname + "','" + nicNo+ "','" + message+ "')"
            );
        } catch (Exception e) {
            e.printStackTrace();
        }

        Notifications
                .getInstance()
                .show(Notifications.Type.SUCCESS,
                        Notifications.Location.TOP_RIGHT, "feedback Added Successfully.");


    }//GEN-LAST:event_roundButton1ActionPerformed

    private boolean fnameValidation(String value) {
        if (value.isEmpty()) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "First Name Is Required");
            return true;
        }
        return false;
    }

    private boolean lnameValidation(String value) {
        if (value.isEmpty()) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Last Name Is Required");
            return true;
        }
        return false;
    }

    private boolean nicValidate(String value) {
        if (value.isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT,
                    "NIC is required.");
            return true;
        } else if (!value.matches(Validation.NICNUMBER_VALIDATION.validate())) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT,
                    "NIC Number Not Valid!");
            return true;
        }
        return false;
    }
    
    
        private boolean feedbackValidate(String value) {
        if (value.isEmpty()) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Feedback Is Required");
            return true;
        }
        return false;
    }


