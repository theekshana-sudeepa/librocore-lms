    private void loadMainCat() {
        try {

            ResultSet resultSet = MySQL.search("SELECT * FROM `main_category`");

            Vector v = new Vector();
            v.add("Select Main Category");
            while (resultSet.next()) {
                v.add(resultSet.getString("name"));
                bookMainCatrMapp.put(resultSet.getString("name"), resultSet.getInt("id"));
            }

            DefaultComboBoxModel model = new DefaultComboBoxModel(v);
            catComboBox.setModel(model);

        } catch (Exception e) {
            //System.out.println("Connection Problem");
            e.printStackTrace();
        }
    }

