    private void roundButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_roundButton1ActionPerformed

        String subcolorname = subCatColor.getText();
        String subcatname = subCatName.getText();

        int subMaincatComboBox = this.catComboBox.getSelectedIndex();

        if (subMaincatComboBox < 1) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT, "Select Main category");
            return;
        }

        if (subbCatNameValidation(subcatname)) {
            return;
        }
        if (subbColorValidation(subcolorname)) {
            return;
        }

        try {

            MySQL.iud("INSERT INTO `sub_category`(`name`,`Color_code`,`main_category_id`) "
                    + "VALUES ('" + subcatname + "','" + subcolorname + "','" + subMaincatComboBox + "')"
            );
            
            Notifications
                .getInstance()
                .show(Notifications.Type.SUCCESS,
                        Notifications.Location.TOP_RIGHT, "Sub Category Added Successfully.");
            
        } catch (Exception se) {
                throw new RuntimeException(se);
            }

        
    }//GEN-LAST:event_roundButton1ActionPerformed

    private boolean subbCatNameValidation(String value) {
        if (value.isEmpty()) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Sub Category Name Is Required");
            return true;
        } else if (!value.matches("^[a-zA-Z\\s]+$")) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Only Letters Allowed In Sub Category Name.");
            return true;
        } else {
            return false;
        }
    }

    private boolean subbColorValidation(String value) {
        if (value.isEmpty()) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Sub Category Color Name Is Required");
            return true;
        } else if (!value.matches("^[a-zA-Z\\s]+$")) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Only Letters Allowed In Sub Category Color Name.");
            return true;
        } else {
            return false;
        }
    }

