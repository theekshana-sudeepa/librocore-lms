    private boolean bCatNameValidation(String value) {
        if (value.isEmpty()) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Main Category Name Is Required");
            return true;
        } else if (!value.matches("^[a-zA-Z\\s]+$")) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Only Letters Allowed In Main Category Name.");
            return true;
        } else {
            return false;
        }
    }


    private boolean bColorValidation(String value) {
        if (value.isEmpty()) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Main Category Color Name Is Required");
            return true;
      } else if (!value.matches("^[a-zA-Z\\s]+$")) {
            Notifications
                    .getInstance()
                    .show(Notifications.Type.WARNING,
                            Notifications.Location.TOP_RIGHT, "Only Letters Allowed In Main Category Color Name.");
            return true;
        } else {
            return false;
        }
    }


