    private void loaduserCount() {

        try {

            ResultSet resultSet = MySQL.search("SELECT COUNT(`nic_no`) FROM `user` WHERE `user`.`status_id`= '1' ");
            if (resultSet.next()) {
                String count = resultSet.getString(1);
                UserCount.setText(count);

            }

        } catch (Exception e) {
            e.printStackTrace();
        }

    }

    private void loadbookCount() {

        try {

            ResultSet resultSet = MySQL.search("SELECT COUNT(`id`) FROM `book` ");
            if (resultSet.next()) {
                String count = resultSet.getString(1);
                bookCount.setText(count);

            }

        } catch (Exception e) {
            e.printStackTrace();
        }

    }
    
