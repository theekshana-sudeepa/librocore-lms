    private void loadBookDetails() {
        try {
            ResultSet bookresult = MySQL.search("SELECT * FROM `book` INNER JOIN `main_category` ON `book`.`main_category_id`=`main_category`.`id` INNER JOIN `sub_category` ON `book`.`sub_category_id`=`sub_category`.`id`");
            DefaultTableModel tableModel = (DefaultTableModel) getBookTable().getModel();
            tableModel.setRowCount(0);
            int count = 0;

            while (bookresult.next()) {
                Vector<String> bookList = new Vector();
                bookList.add(bookresult.getString("id"));
                bookList.add(bookresult.getString("name"));
                bookList.add(bookresult.getString("main_category.name"));
                bookList.add(bookresult.getString("sub_category.name"));
                bookList.add(bookresult.getString("book_author"));
                bookList.add(bookresult.getString("published_date"));
                bookList.add(bookresult.getString("added_date"));
                bookList.add(bookresult.getString("price"));

                tableModel.addRow(bookList);

            }

        } catch (SQLException e) {
            throw new RuntimeException("User Details loading failed");
        }
    }

