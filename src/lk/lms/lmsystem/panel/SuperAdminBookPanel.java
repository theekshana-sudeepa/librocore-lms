    private void bookTableSMMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_bookTableSMMouseClicked
        // TODO add your handling code here:

        if (evt.getClickCount() == 2) {
            int selectedRow = getBookTable().getSelectedRow();
            String bookID = (String) getBookTable().getValueAt(selectedRow, 0);
            String bookName = (String) getBookTable().getValueAt(selectedRow, 1);
            String bookCat = (String) getBookTable().getValueAt(selectedRow, 2);
            String bookSubCat = (String) getBookTable().getValueAt(selectedRow, 3);
            String bookAuthor = (String) getBookTable().getValueAt(selectedRow, 4);
            String bookPublishedDate = (String) getBookTable().getValueAt(selectedRow, 5);
//            String bookQty = (String) bookTable.getValueAt(selectedRow, 7);
            String bookPrice = (String) getBookTable().getValueAt(selectedRow, 7);

            BookAddSM bookadd = new  BookAddSM(superAdminDashboard, true, this);
            bookadd.setLocationRelativeTo(superAdminDashboard);

            bookadd.getaddButton().setEnabled(false);
            bookadd.getbookidfield().setText(bookID);
            bookadd.getbookidfield().setVisible(false);
            bookadd.getBookNamefield().setText(bookName);
            bookadd.getBookAuthorfield().setText(bookAuthor);
//            bookadd.getBookQtyfield().setText(bookQty);
            bookadd.getBookPricefield().setText(bookPrice);
            bookadd.getBookCatcombo().setSelectedItem(bookCat);
            bookadd.getBookSubCatcombo().setSelectedItem(bookSubCat);
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

            try {
                Date date = sdf.parse(bookPublishedDate);
//            jDateChooser2.setDate(date);
                bookadd.getPubDatechooser().setDate(date);
//             bookadd.getPubDatechooser().setText(bookPublishedDate);
            } catch (ParseException e) {
                e.printStackTrace();
            }

            bookadd.setVisible(true);
        }
    }//GEN-LAST:event_bookTableSMMouseClicked

