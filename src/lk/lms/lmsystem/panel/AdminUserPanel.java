    private void userTableMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_userTableMouseClicked
        // TODO add your handling code here:
        if (evt.getClickCount() == 2) {
            int selectedRow = getUserTable().getSelectedRow();
            String userID = (String) getUserTable().getValueAt(selectedRow, 0);
            String userName = (String) getUserTable().getValueAt(selectedRow, 1);
            String userNIC = (String) getUserTable().getValueAt(selectedRow, 2);
            String userDOB = (String) getUserTable().getValueAt(selectedRow, 3);
            String userGender = (String) getUserTable().getValueAt(selectedRow, 4);
            String userStatus = (String) getUserTable().getValueAt(selectedRow, 6);

            String[] split = userName.split(" ");
            String userfirstName = split[0];
            String userlastName = split[1];

            String userEmail = "";
            String userMobile1 = "";
            String userMobile2 = "";
            String usersGender = "";
            String usersStatus = "";
            String userProvince = "";
            String userDistrict = "";
            String userCity = "";
            String userPostCode = "";
            String userline1 = "";
            String userline2 = "";

            try {
                ResultSet userDetails = MySQL.search("SELECT * FROM `user` WHERE `user`.`nic_no`='" + userNIC + "' ");
                if (userDetails.next()) {
                    userEmail = userDetails.getString("email");

                }
            } catch (SQLException e) {
                throw new RuntimeException(e);
            }

            try {
                ResultSet mobileDetails = MySQL.search("SELECT * FROM `contact_number` WHERE `user_nic_no` = "
                        + "(SELECT `nic_no` FROM `user` WHERE `user`.`nic_no`='" + userNIC + "')");
                if (mobileDetails.next()) {
                    userMobile1 = mobileDetails.getString("pNumber01");
                    userMobile2 = mobileDetails.getString("pNumber02");
                }
            } catch (SQLException e) {
                throw new RuntimeException(e);
            }

            try {
                ResultSet genderDetails = MySQL.search("SELECT * FROM `gender` WHERE `id` = "
                        + "(SELECT `nic_no` FROM `user` WHERE `user`.`nic_no`='" + userNIC + "')");
                if (genderDetails.next()) {
                    usersGender = genderDetails.getString("name");

                }
            } catch (SQLException e) {
                throw new RuntimeException(e);
            }

            try {
                ResultSet statusDetails = MySQL.search("SELECT * FROM `status` WHERE `id` = "
                        + "(SELECT `nic_no` FROM `user` WHERE `user`.`nic_no`='" + userNIC + "')");
                if (statusDetails.next()) {
                    usersStatus = statusDetails.getString("name");

                }
            } catch (SQLException e) {
                throw new RuntimeException(e);
            }

            try {
                ResultSet addressDetails = MySQL.search("SELECT * FROM `address` INNER JOIN `province` ON `address`.`province_id`=`province`.`id` "
                        + "INNER JOIN `district` ON `address`.`district_id`=`district`.`id` INNER JOIN `city` ON `address`.`city_id`=`city`.`id` WHERE `user_nic_no` = "
                        + "(SELECT `nic_no` FROM `user` WHERE `user`.`nic_no`='" + userNIC + "')");
                if (addressDetails.next()) {
                    userProvince = addressDetails.getString("province.name");
                    userDistrict = addressDetails.getString("district.name");
                    userCity = addressDetails.getString("city.name");
                    userline1 = addressDetails.getString("lane_1");
                    userline2 = addressDetails.getString("lane_2");
                    userPostCode = addressDetails.getString("postal_code");

                }
            } catch (SQLException e) {
                throw new RuntimeException(e);
            }

            userAddDialog theUserAddDialog = new userAddDialog(adminDashboard, true, this);
            theUserAddDialog.setLocationRelativeTo(adminDashboard);

            theUserAddDialog.getaddButton().setEnabled(false);
//            SMUseraddDialog.getbookidfield().setText(bookID);
//            SMUseraddDialog.getbookidfield().setVisible(false);
            theUserAddDialog.getuserfNamefield().setText(userfirstName);
            theUserAddDialog.getuserlNamefield().setText(userlastName);
            theUserAddDialog.getUserNICfield().setText(userNIC);
            theUserAddDialog.getUserEmailfield().setText(userEmail);
            theUserAddDialog.getUserMobileOnefield().setText(userMobile1);
            theUserAddDialog.getUserMobileTwofield().setText(userMobile2);

            theUserAddDialog.getUserGendercombo().setSelectedItem(usersGender);
            theUserAddDialog.getUserStatuscombo().setSelectedItem(usersStatus);

            theUserAddDialog.getUserProvincecombo().setSelectedItem(userProvince);
            theUserAddDialog.getUserDistrictcombo().setSelectedItem(userDistrict);
            theUserAddDialog.getUserCitycombo().setSelectedItem(userCity);
            theUserAddDialog.getUserLineONefield().setText(userline1);
            theUserAddDialog.getUserLineTwofield().setText(userline2);
            theUserAddDialog.getUserPostCodefield().setText(userPostCode);

            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");

            try {
                Date date = sdf.parse(userDOB);
//            jDateChooser2.setDate(date);
                theUserAddDialog.getUserDOBhooser().setDate(date);
//             bookadd.getPubDatechooser().setText(bookPublishedDate);
            } catch (ParseException e) {
                e.printStackTrace();
            }

            theUserAddDialog.setVisible(true);
        }
    }//GEN-LAST:event_userTableMouseClicked

