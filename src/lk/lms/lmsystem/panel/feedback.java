    private void loadData() {
        try {
            ResultSet resultSet = MySQL.search("SELECT * FROM `feedback`");

            DefaultTableModel model = (DefaultTableModel) feedbackTable.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {

                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("id"));
                vector.add(resultSet.getString("fname") + " " + resultSet.getString("lname"));
                vector.add(resultSet.getString("nic_no"));
                vector.add(resultSet.getString("message"));

                model.addRow(vector);
            }
        } catch (Exception e) {
        }
    }

