    private String resolveMySqlExecutable(String toolName) {
        String binDir = System.getenv("MYSQL_BIN_DIR");
        if (binDir != null && !binDir.isBlank()) {
            File candidate = new File(binDir, toolName);
            if (candidate.exists()) {
                return candidate.getAbsolutePath();
            }
            File winCandidate = new File(binDir, toolName + ".exe");
            if (winCandidate.exists()) {
                return winCandidate.getAbsolutePath();
            }
        }
        return toolName;
    }

    private void RestoreActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RestoreActionPerformed
        if (path == null || path.isBlank()) {
            Notifications.getInstance().show(
                    Notifications.Type.WARNING,
                    Notifications.Location.TOP_RIGHT,
                    "Please select a SQL backup file first."
            );
            return;
        }

        String mysqlBin = resolveMySqlExecutable("mysql");
        ProcessBuilder pb = new ProcessBuilder(
                mysqlBin,
                "-h", MySQL.getHost(),
                "-P", MySQL.getPort(),
                "-u", MySQL.getUser(),
                MySQL.getDatabase()
        );
        if (MySQL.getPassword() != null && !MySQL.getPassword().isEmpty()) {
            pb.environment().put("MYSQL_PWD", MySQL.getPassword());
        }
        pb.redirectInput(new File(path));

        try {
            Process runtimeProcess = pb.start();
            int processComplete = runtimeProcess.waitFor();

            if (processComplete == 0) {
                Notifications.getInstance().show(
                        Notifications.Type.SUCCESS,
                        Notifications.Location.TOP_RIGHT,
                        "Database Restored Successfully."
                );
            } else {
                Notifications.getInstance().show(
                        Notifications.Type.ERROR,
                        Notifications.Location.TOP_RIGHT,
                        "Database Restore Failed. Verify MySQL CLI tools and credentials."
                );
            }
        } catch (Exception e) {
            e.printStackTrace();
            Notifications.getInstance().show(
                    Notifications.Type.ERROR,
                    Notifications.Location.TOP_RIGHT,
                    "Restore Error: " + e.getMessage()
            );
        }

        restoreField.setText("");
    }//GEN-LAST:event_RestoreActionPerformed

    private void roundButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_roundButton2ActionPerformed
        if (path == null || path.isBlank()) {
            Notifications.getInstance().show(
                    Notifications.Type.WARNING,
                    Notifications.Location.TOP_RIGHT,
                    "Please choose a backup destination first."
            );
            return;
        }

        String mysqldumpBin = resolveMySqlExecutable("mysqldump");
        ProcessBuilder pb = new ProcessBuilder(
                mysqldumpBin,
                "-h", MySQL.getHost(),
                "-P", MySQL.getPort(),
                "-u", MySQL.getUser(),
                "--add-drop-database",
                "-B", MySQL.getDatabase(),
                "-r", path
        );
        if (MySQL.getPassword() != null && !MySQL.getPassword().isEmpty()) {
            pb.environment().put("MYSQL_PWD", MySQL.getPassword());
        }

        try {
            Process p = pb.start();
            int processComplete = p.waitFor();
            if (processComplete == 0) {
                Notifications.getInstance().show(
                        Notifications.Type.SUCCESS,
                        Notifications.Location.TOP_RIGHT,
                        "Database Backed Up Successfully."
                );
            } else {
                Notifications.getInstance().show(
                        Notifications.Type.ERROR,
                        Notifications.Location.TOP_RIGHT,
                        "Database Backup Failed. Verify mysqldump is on PATH."
                );
            }
        } catch (Exception e) {
            e.printStackTrace();
            Notifications.getInstance().show(
                    Notifications.Type.ERROR,
                    Notifications.Location.TOP_RIGHT,
                    "Backup Error: " + e.getMessage()
            );
        }
        backupField.setText("");
    }//GEN-LAST:event_roundButton2ActionPerformed


