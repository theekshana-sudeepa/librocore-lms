    private void loadData() {
        try {
            ResultSet userresult = MySQL.search("SELECT * FROM `user` INNER JOIN `gender` ON `user`.`gender_id`=`gender`.`id` INNER JOIN `status` ON `user`.`status_id`=`status`.`id`");
            DefaultTableModel tableModel = (DefaultTableModel) getUserTable().getModel();
            tableModel.setRowCount(0);
            int count = 0;

            while (userresult.next()) {
                Vector<String> UserList = new Vector();
                UserList.add(userresult.getString("nic_no"));
                UserList.add(userresult.getString("fName") + " " + userresult.getString("lName"));
                UserList.add(userresult.getString("nic_no"));
                UserList.add(userresult.getString("dob"));
                UserList.add(userresult.getString("gender.name"));
                UserList.add(userresult.getString("joined_date"));
                UserList.add(userresult.getString("status.name"));
                tableModel.addRow(UserList);

            }

        } catch (SQLException e) {
            throw new RuntimeException("User Details loading failed");
        }
    }

