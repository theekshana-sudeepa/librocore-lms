    private void issueBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_issueBtnActionPerformed
        String uid=searchBar1.getText();
        String bookid = bookID.getText();
        String issue_date = ((JTextField) issueDate.getDateEditor().getUiComponent()).getText();
        String return_date = ((JTextField) returnDate.getDateEditor().getUiComponent()).getText();

        try {
            ResultSet resultSet = MySQL.search("SELECT * FROM `b_issued` WHERE `user_nic_no`='" + uid + "' AND `book_id`='" + bookid + "' "
                    + "AND `issued_date`='" + issue_date + "' AND `return_date`='" + return_date + "'");
            if (resultSet.next()) {
                Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT, "This book is already issued to the reader");
            } else {
                MySQL.iud("INSERT INTO `b_issued`(`user_nic_no`,`book_id`,`issued_date`,`return_date`,`reciept_path`) "
                        + "VALUES('" + uid + "','" + bookid + "','" + issue_date + "','" + return_date + "','1')");

                Notifications.getInstance().show(Notifications.Type.SUCCESS, Notifications.Location.TOP_RIGHT, "Book Issued Successfully");
                loadData();
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
//        System.out.println(uid);
//        System.out.println(bookid);
//        System.out.println(issue_date);
//        System.out.println(return_date);

    }//GEN-LAST:event_issueBtnActionPerformed

    private void searchBar1KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_searchBar1KeyReleased

        if (evt.getKeyCode() == KeyEvent.VK_ENTER) {
            
            try {
                
                ResultSet result = MySQL.search("SELECT * FROM `user`"
                        + "INNER JOIN `address` ON `user`.`nic_no`=`address`.`user_nic_no` "
                        + "INNER JOIN `city` ON `address`.`city_id`=`city`.`id`"
                        + "WHERE `user`.`nic_no`='" + (searchBar1.getText()) + "'");

                if (result.next()) {
                    
                        Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT, "This is a Book ID");
                    name.setText(result.getString("user.fname") + " " + result.getString("user.lname"));
                    email.setText(result.getString("user.email"));
                    address.setText(result.getString("address.lane_1") + " " + result.getString("address.lane_2") + " " + result.getString("city.name"));
                    
                    searchBar1.setEnabled(false);
                    searchBar2.grabFocus();
                }else{
                    ResultSet resultbook = MySQL.search("SELECT * FROM `book`"
                        + "INNER JOIN `main_category` ON `book`.`main_category_id`=`main_category`.`id` "
                        + "INNER JOIN `sub_category` ON `book`.`sub_category_id`=`sub_category`.`id`"
                        + "WHERE `book`.`id`='" + (searchBar1.getText()) + "'");
                    
                    if (resultbook.next()) {
                        
                        Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT, "This is a Book ID");
                    }
                        
                }

            } catch (SQLException e) {
                throw new RuntimeException(e);
            }
        }
    }//GEN-LAST:event_searchBar1KeyReleased

    private void searchBar2KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_searchBar2KeyReleased

        if (evt.getKeyCode() == KeyEvent.VK_ENTER) {

            try {

                Date isdate = new Date();
                issueDate.addPropertyChangeListener(new PropertyChangeListener() {
                    @Override
                    public void propertyChange(PropertyChangeEvent evt) {
                        if (evt.getPropertyName().equals("date")) {
                            Date selectedDate = (Date) evt.getNewValue();
                            Calendar cal = Calendar.getInstance();
                            cal.setTime(selectedDate);
                            cal.add(Calendar.DAY_OF_YEAR, 14);
                            Date newDate = cal.getTime();
                            returnDate.setDate(newDate);
                        }
                    }
                });

                ResultSet result = MySQL.search("SELECT * FROM `book`"
                        + "INNER JOIN `main_category` ON `book`.`main_category_id`=`main_category`.`id` "
                        + "INNER JOIN `sub_category` ON `book`.`sub_category_id`=`sub_category`.`id`"
                        + "WHERE `book`.`id`='" + (searchBar2.getText()) + "'");

                if (result.next()) {
                    bookID.setText(result.getString("book.id"));
                    title.setText(result.getString("book.name"));
                    category.setText(result.getString("main_category.name") + " " + result.getString("sub_category.name"));
                    issueDate.setDate(isdate);
                    searchBar1.setEnabled(false);
                    searchBar2.setEnabled(false);
                    issueDate.setEnabled(false);
                    returnDate.setEnabled(false);
                }

            } catch (SQLException e) {
                throw new RuntimeException(e);
            }
        }
    }//GEN-LAST:event_searchBar2KeyReleased

