    private void loadData() {
        try {
            ResultSet resultSet = MySQL.search("SELECT * FROM `b_issued`"
                    + "INNER JOIN `book` ON `b_issued`.`book_id`=`book`.`id`");

            DefaultTableModel model = (DefaultTableModel) assignTable.getModel();
            model.setRowCount(0);

            while (resultSet.next()) {

                Vector<String> vector = new Vector<>();
                vector.add(resultSet.getString("id"));
                vector.add(resultSet.getString("user_nic_no"));
                vector.add(resultSet.getString("book_id"));
                vector.add(resultSet.getString("book.name"));
                vector.add(resultSet.getString("issued_date"));
                vector.add(resultSet.getString("return_date"));

                model.addRow(vector);
            }
        } catch (Exception e) {
        }
    }
