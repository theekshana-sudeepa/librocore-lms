    private void signInActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_signInActionPerformed
        // TODO add your handling code here:

        String usernamee = this.username.getText();
        String password = String.valueOf(roundPasswordField1.getPassword());

        if (usernameValidate(usernamee)) {
            return;
        }
        if (passwordValidate(password)) {
            return;
        }

        try {
            ResultSet logindetails = MySQL.search("SELECT * FROM `login_details` WHERE `username`='" + usernamee + "' AND `password`='" + password + "'");
            if (logindetails.next()) {
                ResultSet userdetails = MySQL.search("SELECT * FROM `user` INNER JOIN `status` ON `user`.`status_id`=`status`.`id` INNER JOIN `user_type` ON `user`.`user_type_id`=`user_type`.`id` WHERE `user`.`id`='" + logindetails.getString("user_id") + "'");
                if (userdetails.next()) {

                    if (userdetails.getString("name").equals(Status.ACTIVE.name())) {
                        if (userdetails.getString("type").equals(UserType.SUPERADMIN.name())) {
                            new SuperAdminDashboard().setVisible(true);
                            this.dispose();
                        } else if (userdetails.getString("type").equals(UserType.ADMIN.name())) {
                            new AdminDashboard().setVisible(true);
                            this.dispose();

                        } else {
                            Notifications
                                    .getInstance()
                                    .show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT, "Your session is not activated. Please contact administrator.");
                        }
                    }
                }
            }
        } catch (SQLException se) {
            throw new RuntimeException();
        }
    }//GEN-LAST:event_signInActionPerformed

