    private boolean usernameValidate(String value) {
        if (value.isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT,
                    "Username is required");
            return true;
        } else if (value.length() < 4) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT,
                    "Username can't be less than four characteristics!");
            return true;
        }
        return false;
    }

    private boolean passwordValidate(String value) {
        if (value.isEmpty()) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT,
                    "Password is required");
            return true;
        } else if (!value.matches(Validation.PASSWORD_VALIDATION.validate())) {
            Notifications.getInstance().show(Notifications.Type.WARNING, Notifications.Location.TOP_RIGHT,
                    "Provide valid password!");
            return true;
        }
        return false;
    }

