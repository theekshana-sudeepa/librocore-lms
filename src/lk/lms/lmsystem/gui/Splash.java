    private void progress() {
        new Thread(() -> {
            for (int i = 0; i <= 100; i++) {
                jProgressBar1.setValue(i);

                switch (i) {
                    case 10:
                        jLabel2.setText("Loading . . .");
                        break;
                    case 37:
                        jLabel2.setText("Database Connection Succeed . . .");
                        break;
                    case 50:
                        jLabel2.setText("Report Libraries Loaded . . .");
                        break;
                    case 80:
                        jLabel2.setText("Done . . .");
                        break;

                }
                try {
                    Thread.sleep(10);
                } catch (InterruptedException e) {
                    throw new RuntimeException(e);
                }
            }
            new Signin().setVisible(true);
            this.dispose();
        }).start();
    }

